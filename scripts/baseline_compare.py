"""Run the README's sample questions two ways and write the comparison into the README:

  1. Ticker Tutor's research team (Lead → parallel Researchers → Writer → Verifier, with tools)
  2. The same Gemini model with no tools and no system prompt

    uv run python scripts/baseline_compare.py            # needs gcloud auth (Vertex AI) and the real database
    uv run python scripts/baseline_compare.py --only 2   # just one sample

It replaces the block between <!-- baseline:start --> and <!-- baseline:end --> in README.md and
saves the full transcripts (with every tool call) to docs/baseline.md.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SAMPLES = [
    "Walk me through Microsoft's (MSFT) trend over the past year using moving averages and RSI, and compare its volatility with the S&P 500's.",
    "Does buying the dip work for S&P 500 stocks? What has happened after big one-day drops?",
    "Why is Nvidia down so much lately?",
]


def baseline(question: str) -> str:
    from google.genai import types

    from tickertutor import config, llm
    return (llm.generate(question, types.GenerateContentConfig(), config.GEMINI_THINKING).text or "").strip()


def quote(text: str) -> str:
    return "\n".join("> " + line if line.strip() else ">" for line in text.strip().splitlines())


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", type=int, choices=[1, 2, 3], help="run one sample (1-3)")
    args = ap.parse_args()
    from tickertutor import agents, config
    from tickertutor.data import db

    meta = db().meta()
    if meta.get("synthetic"):
        print("Warning: the database is the synthetic demo. Build real data first (scripts/build_data.py).")
    picks = [args.only] if args.only else [1, 2, 3]
    blocks, full = [], [f"# Baseline comparison\n\nModel: `{config.GEMINI_MODEL}`. Data as of {meta.get('as_of')}.\n"]
    for i in picks:
        q = SAMPLES[i - 1]
        print(f"[{i}] {q}\n  research team…", flush=True)
        t0 = time.time()
        res = agents.answer(q)
        secs = time.time() - t0
        calls = res["tool_calls"]
        researchers = len({c["agent"] for c in calls if c["agent"].startswith("researcher")})
        data_calls = sum(1 for c in calls if c["agent"].startswith("researcher"))
        n_sources = len(re.findall(r"^\d+\. ", res["response"].split("**Sources**")[-1], re.M)) if "**Sources**" in res["response"] else 0
        print("  same model, no tools…", flush=True)
        base = baseline(q)
        blocks.append(
            f"#### Sample {i}: {q}\n\n"
            f"Research team: {researchers} researchers, {data_calls} tool calls, {n_sources} cited sources, {secs:.0f} s. "
            f"Same model without tools: no data access, no citations.\n\n"
            f"<details><summary><b>Ticker Tutor's answer</b></summary>\n\n{res['response']}\n\n</details>\n\n"
            f"<details><summary><b>Same model, no tools, no system prompt</b></summary>\n\n{quote(base)}\n\n</details>\n")
        full.append(f"## {i}. {q}\n\n### Ticker Tutor\n\n{res['response']}\n\n### Tool calls\n\n```json\n"
                    + json.dumps(calls, indent=1, default=str)[:60000] + f"\n```\n\n### Same model, no tools\n\n{base}\n")
    stamp = f"_Generated by `scripts/baseline_compare.py` with `{config.GEMINI_MODEL}` on data as of {meta.get('as_of')}._\n\n"
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    new = "<!-- baseline:start -->\n" + stamp + "\n".join(blocks) + "<!-- baseline:end -->"
    text = re.sub(r"<!-- baseline:start -->.*?<!-- baseline:end -->", lambda m: new, text, flags=re.S)
    readme.write_text(text, encoding="utf-8")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "baseline.md").write_text("\n".join(full), encoding="utf-8")
    print("Updated README.md and docs/baseline.md")


if __name__ == "__main__":
    main()
